"""Generate frontend projections from the read-only OpenAPI contract (requires PyYAML)."""
from pathlib import Path
import json
import re
import yaml
root = Path(__file__).resolve().parents[2]
schemas = yaml.safe_load((root / 'docs/api/openapi.yaml').read_text())['components']['schemas']
selected = ['CompanyProfile', 'CompanyProfileUpdate', 'InterviewerProfile', 'InterviewerProfileUpdate', 'InterviewerPage', 'CompanyRegistrationPage', 'ManagedAccountPage', 'FinalistPage', 'ApplicationScorecard', 'PipelineDashboard', 'GradingSubmissionPage', 'InterviewPage', 'InterviewFeedback', 'AssessmentInstancePage', 'ApplicationComparison', 'JobApplicationPage', 'PipelineExecutionPage', 'StageTransition', 'PipelineValidation', 'PipelineMigrationPreview', 'StageExecutionPage', 'CandidateStageProgressView', 'ComparisonView', 'ManagedApplicationPage', 'FeedbackView']
seen = set()
def convert(s):
    if '$ref' in s:
        name = s['$ref'].rsplit('/', 1)[-1]
        add(name)
        return name
    if 'enum' in s: return ' | '.join(json.dumps(v) for v in s['enum'])
    for k, join in [('oneOf',' | '), ('anyOf',' | '), ('allOf',' & ')]:
        if k in s: return join.join('('+convert(x)+')' for x in s[k])
    t=s.get('type')
    if isinstance(t,list): return ' | '.join(convert({**s,'type':x}) for x in t)
    if t=='array': return '('+convert(s.get('items',{}))+')[]'
    if t in ['integer','number']: return 'number'
    if t in ['boolean','string','null']: return t
    if t=='object' or 'properties' in s:
        req=s.get('required',[])
        props=[json.dumps(k)+('' if k in req else '?')+': '+convert(v)+';' for k,v in s.get('properties',{}).items()]
        if not props: return 'Record<string, unknown>'
        return '{\n'+'\n'.join('  '+p for p in props)+'\n}'
    return 'unknown'
out=[]
def add(name):
    if name in seen or name not in schemas:return
    seen.add(name)
    value=convert(schemas[name]); out.append('export type '+name+' = '+value+';')
for n in selected:add(n)
(root/'web/src/shared/lib/contract.types.ts').write_text('// Generated by web/scripts/contract-types.py from docs/api/openapi.yaml.\n// A contract type does not imply that a planned operation is registered.\n\n'+'\n\n'.join(out)+'\n')
print('Generated',len(seen),'contract projections')
